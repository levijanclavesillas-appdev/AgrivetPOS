// The Lucide icons this product uses, and only those — TASK-050.
//
//   node tools/icons/build.js /path/to/lucide-static/icon-nodes.json
//
// Lucide (https://lucide.dev, ISC) is not a dependency and is not installed by
// `npm install`: `05_TECH_SPEC.md` §2 keeps this product at four runtime dependencies,
// no build step, and — through the renderer's CSP — no remote asset. So the icons are
// **vendored**: `npm pack lucide-static@1.45.0` anywhere, point this at the
// `icon-nodes.json` inside, and it writes two files from the names the renderer asks for.
//
//   public/js/shell/icons.js   every name used from JavaScript — `icon: 'printer'` on an
//                              `h()` call, `iconEnd: …`, or `icon('…')` / `iconSvg('…')`
//   public/css/icons.css       every name used from CSS — `var(--icon-…)`, as a data: URI
//                              the stylesheets use as a mask, so a status class such as
//                              `.close-verdict.beyond` carries its icon wherever it is used
//
// Scanning rather than listing, so an icon is added by using it and removed by no longer
// using it, and the vendored set is never larger than the product. `renderer.test.js`
// fails if the renderer names an icon these files do not have — run this again then.

